                    exit_image = pygame.image.load('cil.png')
                    exit_image = pygame.transform.scale(exit_image, (velikost_policka, velikost_policka))
                    Herni_okno.blit(exit_image, (sloupce * velikost_policka, radky * velikost_policka))

