# Herní proměnné
main_screen = True
game_screen = False

Hrac_velikost = 25
Hrac_X = 40
Hrac_Y = 40
Hrac_speed = 2

Hrac_textura = pygame.image.load('hrac.png')
Hrac_textura = pygame.transform.scale(Hrac_textura, (Hrac_velikost, Hrac_velikost))

def check_level_complete():
    """Kontrola, zda hráč dokončil úroveň"""
    global aktualni_lvl, maze, Hrac_X, Hrac_Y, main_screen, game_screen
    
    misto_x = (len(maze[0]) - 2) * velikost_policka
    misto_y = (len(maze) - 2) * velikost_policka

    if Hrac_X >= misto_x - 10 and Hrac_Y >= misto_y - 10:
        if aktualni_lvl + 1 < len(maze_lvls):  
            aktualni_lvl += 1
            maze = maze_lvls[aktualni_lvl]
            Hrac_X, Hrac_Y = 40, 40  # Reset pozice hráče
        else:
            # Po dokončení všech úrovní se vrátí do menu
            main_screen = True
            game_screen = False
            aktualni_lvl = 0
            maze = maze_lvls[aktualni_lvl]
            Hrac_X, Hrac_Y = 40, 40

def byla_kolize(nove_x, nove_y):
    """Zkontroluje, zda hráč narazí do zdi"""
    body_ke_kontrole  = [         
        (nove_x, nove_y),  
        (nove_x + Hrac_velikost - 1, nove_y),  
        (nove_x, nove_y + Hrac_velikost - 1),  
        (nove_x + Hrac_velikost - 1, nove_y + Hrac_velikost - 1)  
    ]

    for bx, by in body_ke_kontrole:
        maze_x = bx // velikost_policka
        maze_y = by // velikost_policka
        if maze[maze_y][maze_x] == 1:  
            return True  
    
    return False  

# Hlavní smyčka
smycka = True
while smycka:
    for event in pygame.event.get():
        if event.type == QUIT:
            smycka = False

        if event.type == MOUSEBUTTONDOWN:
            if quit_button_rect.collidepoint(event.pos):  
                smycka = False  
            
            if start_button_rect.collidepoint(event.pos):
                game_screen = True  
                main_screen = False

    if main_screen:
        Obraz.blit(Background_menu, (0, 0))
        Obraz.blit(start_button, start_button_rect.topleft)
        Obraz.blit(quit_button, quit_button_rect.topleft)

    if game_screen:
        Herni_okno.fill(GREEN)  

        # Vykreslení bludiště
        for radky in range(len(maze)):
            for sloupce in range(len(maze[radky])):
                if maze[radky][sloupce] == 1:
                    pygame.draw.rect(Herni_okno, BLACK, (sloupce * velikost_policka, radky * velikost_policka, velikost_policka, velikost_policka))

        # Pohyb hráče
        keys = pygame.key.get_pressed()
        new_x, new_y = Hrac_X, Hrac_Y  

        if keys[K_w]:
            new_y -= Hrac_speed
        if keys[K_s]:
            new_y += Hrac_speed
        if keys[K_a]:
            new_x -= Hrac_speed
        if keys[K_d]:
            new_x += Hrac_speed

        if not byla_kolize(new_x, new_y):  
            Hrac_X, Hrac_Y = new_x, new_y  

        Herni_okno.blit(Hrac_textura, (Hrac_X, Hrac_Y))

        check_level_complete()

        Obraz.blit(Herni_okno, (Hlavni_screen_X // 2 - Herni_okno_X // 2, Hlavni_screen_Y // 2 - Herni_okno_Y // 2))
        
    pygame.display.update()

pygame.quit()
